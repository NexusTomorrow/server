using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace NexusTomorrow.Network.Codec.Generator;

/// <summary>
/// Writes the generated half of each wire type, and the per-assembly message registry.
/// </summary>
internal static class SourceEmitter
{
    private const string Codec = WireNames.GlobalCodec;
    private const string Immutable = "global::System.Collections.Immutable.ImmutableArray";

    public static string EmitType(TypeModel type, LayoutCalculator layouts)
    {
        LayoutModel layout = layouts.LayoutOf(type);
        var writer = new SourceWriter();
        writer.Line("// <auto-generated/>").Line("#nullable enable").Line();

        bool hasNamespace = type.Namespace.Length > 0;
        if (hasNamespace)
            writer.Open($"namespace {type.Namespace}");
        foreach (ContainingTypeModel containing in type.ContainingTypes)
            writer.Open($"partial {containing.Keyword} {containing.Name}");

        writer.Line(LayoutDataAttribute(layout));
        string baseList = (type.WireBase, type.Message) switch
        {
            (null, null) => $" : {Codec}.IWireStruct",
            (_, not null) => $" : {Codec}.IWireMessage",
            _ => "",
        };
        writer.Open($"partial {type.Keyword} {type.Name}{baseList}");

        if (type.Message is { } message)
            EmitMessageMembers(writer, message, layout);

        string modifiers = type.WireBase is not null ? "public override" : type.IsSealed ? "public" : "public virtual";
        EmitRead(writer, type, layouts, modifiers);
        writer.Line();
        EmitWrite(writer, type, layouts, modifiers);
        writer.Line();
        EmitMeasure(writer, type, layouts, layout, modifiers);

        writer.Close();
        foreach (ContainingTypeModel _ in type.ContainingTypes)
            writer.Close();
        if (hasNamespace)
            writer.Close();
        return writer.ToString();
    }

    public static string EmitRegistry(string assemblyName, IReadOnlyList<(TypeModel Type, MessageModel Message)> messages)
    {
        var writer = new SourceWriter();
        writer.Line("// <auto-generated/>").Line("#nullable enable").Line();
        writer.Open($"namespace {NamespaceOf(assemblyName)}");
        writer.Line("/// <summary>");
        writer.Line("/// Every message this assembly declares: their layouts, and a factory per direction keyed by opcode.");
        writer.Line("/// </summary>");
        writer.Open("public static class WireMessages");

        writer.Line("/// <summary>");
        writer.Line("/// The layout of every message this assembly declares, in opcode order.");
        writer.Line("/// </summary>");
        if (messages.Count == 0)
        {
            writer.Line($"public static {Immutable}<{Codec}.WireLayout> Layouts {{ get; }} = {Immutable}<{Codec}.WireLayout>.Empty;");
        }
        else
        {
            writer.Line($"public static {Immutable}<{Codec}.WireLayout> Layouts {{ get; }} = {Immutable}.Create(");
            for (int i = 0; i < messages.Count; i++)
                writer.Line($"    LayoutOf<{messages[i].Type.FullName}>(){(i == messages.Count - 1 ? ");" : ",")}");
        }

        EmitFactory(writer, "CreateClientToServer", "a message the client sends", messages.Where(message => (message.Message.Direction & 1) != 0));
        EmitFactory(writer, "CreateServerToClient", "a message the server sends", messages.Where(message => (message.Message.Direction & 2) != 0));

        writer.Line();
        writer.Open($"private static {Codec}.WireLayout LayoutOf<T>() where T : {Codec}.IWireMessage");
        writer.Line("return T.Layout;");
        writer.Close();

        writer.Close();
        writer.Close();
        return writer.ToString();
    }

    private static void EmitFactory(SourceWriter writer, string name, string what, IEnumerable<(TypeModel Type, MessageModel Message)> messages)
    {
        writer.Line();
        writer.Line("/// <summary>");
        writer.Line($"/// Create {what} for <paramref name=\"opcode\"/>, or null when this assembly declares none.");
        writer.Line("/// </summary>");
        writer.Open($"public static {Codec}.IWireMessage? {name}(ushort opcode)");
        writer.Line("return opcode switch");
        writer.Line("{");
        foreach ((TypeModel type, MessageModel message) in messages)
            writer.Line($"    {Hex(message.Opcode)} => new {type.FullName}(),");
        writer.Line("    _ => null,");
        writer.Line("};");
        writer.Close();
    }

    private static void EmitMessageMembers(SourceWriter writer, MessageModel message, LayoutModel layout)
    {
        string widths = string.Join(", ", layout.Widths.Select(width => Num(width)));
        string parts = string.Join(", ", layout.Parts.Select(part =>
            $"new {Codec}.WirePart {{ Shape = ({Codec}.WirePartShape){Num(part.Shape)}, At = {Num(part.At)}, ElementBits = {Num(part.ElementBits)} }}"));

        writer.Line($"private static readonly {Codec}.WireLayout s_generatedLayout = new(");
        writer.Line($"    {Hex(message.Opcode)},");
        writer.Line($"    ({Codec}.Direction){Num(message.Direction)},");
        writer.Line($"    {Bool(layout.IsFixed)},");
        writer.Line($"    {Bool(layout.IsComplete)},");
        writer.Line($"    {Immutable}.Create<byte>({widths}),");
        writer.Line($"    {Immutable}.Create<{Codec}.WirePart>({parts}));");
        writer.Line();
        writer.Line($"// GameMessageOpcode.{message.OpcodeExpression}");
        writer.Line($"static ushort {Codec}.IWireMessage.Opcode => {Hex(message.Opcode)};");
        writer.Line();
        writer.Line($"static {Codec}.Direction {Codec}.IWireMessage.Direction => ({Codec}.Direction){Num(message.Direction)};");
        writer.Line();
        writer.Line($"static {Codec}.WireLayout {Codec}.IWireMessage.Layout => s_generatedLayout;");
        writer.Line();
    }

    private static void EmitRead(SourceWriter writer, TypeModel type, LayoutCalculator layouts, string modifiers)
    {
        writer.Line("/// <inheritdoc/>");
        writer.Open($"{modifiers} void Read(ref {Codec}.BitReader reader)");
        if (type.WireBase is not null)
            writer.Line("base.Read(ref reader);");

        for (int i = 0; i < type.Members.Count; i++)
        {
            MemberModel member = type.Members[i];
            string name = member.Name;
            switch (member.Shape)
            {
                case MemberShape.Value when member.Value is not null:
                    if (member.Value.Kind == ValueKind.Struct)
                    {
                        if (member.Settable)
                            writer.Line($"{name} = new {member.Value.StructType}();");
                        writer.Line($"{name}.Read(ref reader);");
                    }
                    else
                    {
                        writer.Line($"{name} = {ReadValue(member.Value)};");
                    }

                    break;
                case MemberShape.Array when member is { Value: { } element, ElementType: { } elementType }:
                    EmitReadArray(writer, type, member, element, elementType, i, layouts);
                    break;
                case MemberShape.FixedArray when member is { Value: { } element, ElementType: { } elementType }:
                    EmitReadFixedArray(writer, member, element, elementType, i);
                    break;
                case MemberShape.Union:
                    EmitReadUnion(writer, type, member, layouts);
                    break;
                case MemberShape.Blob:
                    writer.Open("");
                    if (member.BlobAlign)
                        writer.Line("reader.AlignToByte();");
                    writer.Line($"long length{i} = (long)reader.ReadBits({Num(member.BlobLengthBits)});");
                    if (member.BlobLengthIncludesSelf)
                        writer.Line($"length{i} -= {Num(member.BlobLengthBits / 8)};");
                    writer.Line($"if (length{i} < 0 || length{i} * 8 > reader.BitsRemaining)");
                    writer.Line($"    throw new {Codec}.CodecException({Quote($"The length of {name} runs past the end of the body.")});");
                    writer.Line($"byte[] bytes{i} = new byte[length{i}];");
                    writer.Line($"reader.ReadBytes(bytes{i});");
                    writer.Line($"{name} = bytes{i};");
                    writer.Close();
                    break;
                case MemberShape.Pad:
                    writer.Line($"for (int skipped{i} = 0; skipped{i} < {Num(member.PadBits)}; skipped{i} += 64)");
                    writer.Line($"    reader.ReadBits(global::System.Math.Min(64, {Num(member.PadBits)} - skipped{i}));");
                    break;
            }
        }

        writer.Close();
    }

    private static void EmitReadArray(SourceWriter writer, TypeModel type, MemberModel member, ValueModel element, string elementType, int i, LayoutCalculator layouts)
    {
        string name = member.Name;
        writer.Open("");
        if (member.CountFrom is null)
        {
            writer.Line($"int count{i} = (int)reader.ReadBits({Num(member.CountBits)});");
        }
        else
        {
            MemberModel? count = type.Members.FirstOrDefault(candidate => candidate.Name == member.CountFrom);
            writer.Line($"int count{i} = unchecked((int){member.CountFrom});");
            writer.Line($"if (count{i} < 0)");
            writer.Line($"    throw new {Codec}.CodecException({Quote($"The count {count?.Name} for {name} is out of range.")});");
        }

        int guaranteed = layouts.GuaranteedBits(element);
        if (guaranteed > 0)
        {
            writer.Line($"if ((long)count{i} * {Num(guaranteed)} > reader.BitsRemaining)");
            writer.Line($"    throw new {Codec}.CodecException({Quote($"The count of {name} asks for more elements than the body holds.")});");
        }

        if (member.Collection == CollectionKind.Array)
            writer.Line($"var array{i} = new {elementType}[count{i}];");
        else if (member.Settable)
            writer.Line($"{name} = new global::System.Collections.Generic.List<{elementType}>(count{i});");
        else
            writer.Line($"{name}.Clear();");

        writer.Open($"for (int i{i} = 0; i{i} < count{i}; i{i}++)");
        EmitReadElement(writer, element, elementType, $"element{i}");
        writer.Line(member.Collection == CollectionKind.Array ? $"array{i}[i{i}] = element{i};" : $"{name}.Add(element{i});");
        writer.Close();

        if (member.Collection == CollectionKind.Array)
            writer.Line($"{name} = array{i};");
        writer.Close();
    }

    private static void EmitReadFixedArray(SourceWriter writer, MemberModel member, ValueModel element, string elementType, int i)
    {
        string name = member.Name;
        string length = Num(member.FixedLength);
        writer.Open("");
        if (member.Settable)
        {
            writer.Line($"var array{i} = new {elementType}[{length}];");
        }
        else
        {
            writer.Line($"if ({name}.Length != {length})");
            writer.Line($"    throw new {Codec}.CodecException({Quote($"{name} must hold {member.FixedLength} elements.")});");
            writer.Line($"var array{i} = {name};");
        }

        writer.Open($"for (int i{i} = 0; i{i} < {length}; i{i}++)");
        EmitReadElement(writer, element, elementType, $"element{i}");
        writer.Line($"array{i}[i{i}] = element{i};");
        writer.Close();
        if (member.Settable)
            writer.Line($"{name} = array{i};");
        writer.Close();
    }

    private static void EmitReadUnion(SourceWriter writer, TypeModel type, MemberModel member, LayoutCalculator layouts)
    {
        MemberModel? selector = type.Members.FirstOrDefault(candidate => candidate.Name == member.UnionSelector);
        if (selector?.Value?.Scalar is not { } scalar)
            return;

        writer.Line($"{member.Name} = {SelectorValue(selector.Name, scalar)} switch");
        writer.Line("{");
        foreach (TypeModel arm in layouts.ArmsOf(member.UnionType))
            writer.Line($"    {UnionCases.Literal(arm.UnionCaseValue, scalar)} => new {arm.FullName}(),");
        writer.Line($"    _ => throw new {Codec}.CodecException(\"No arm of {Plain(member.UnionType)} has the selector value \" + {selector.Name} + \".\"),");
        writer.Line("};");
        writer.Line($"{member.Name}.Read(ref reader);");
    }

    private static void EmitReadElement(SourceWriter writer, ValueModel element, string elementType, string local)
    {
        if (element.Kind == ValueKind.Struct)
        {
            writer.Line($"var {local} = new {elementType}();");
            writer.Line($"{local}.Read(ref reader);");
        }
        else
        {
            writer.Line($"{elementType} {local} = {ReadValue(element)};");
        }
    }

    private static void EmitWrite(SourceWriter writer, TypeModel type, LayoutCalculator layouts, string modifiers)
    {
        writer.Line("/// <inheritdoc/>");
        writer.Open($"{modifiers} void Write(ref {Codec}.BitWriter writer)");
        if (type.WireBase is not null)
            writer.Line("base.Write(ref writer);");

        for (int i = 0; i < type.Members.Count; i++)
        {
            MemberModel member = type.Members[i];
            string name = member.Name;

            if (member is { IsCount: true, Value.Scalar: { } countScalar })
                EmitCountAssignment(writer, type, member, countScalar, i);
            if (member.Value?.Scalar is { } selectorScalar)
            {
                foreach (MemberModel union in type.Members.Where(candidate => candidate.Shape == MemberShape.Union && candidate.UnionSelector == name))
                    EmitSelectorAssignment(writer, name, selectorScalar, union, layouts);
            }

            switch (member.Shape)
            {
                case MemberShape.Value when member.Value is not null:
                    EmitWriteValue(writer, member.Value, name);
                    break;
                case MemberShape.Array when member.Value is not null:
                    if (member.CountFrom is null)
                        writer.Line($"writer.WriteBits((ulong){name}.{CountOf(member)}, {Num(member.CountBits)});");
                    writer.Open($"foreach (var element{i} in {name})");
                    EmitWriteValue(writer, member.Value, $"element{i}");
                    writer.Close();
                    break;
                case MemberShape.FixedArray when member.Value is not null:
                    writer.Line($"if ({name}.Length != {Num(member.FixedLength)})");
                    writer.Line($"    throw new {Codec}.CodecException({Quote($"{name} must hold {member.FixedLength} elements.")});");
                    writer.Open($"foreach (var element{i} in {name})");
                    EmitWriteValue(writer, member.Value, $"element{i}");
                    writer.Close();
                    break;
                case MemberShape.Union:
                    writer.Line($"{name}.Write(ref writer);");
                    break;
                case MemberShape.Blob:
                    if (member.BlobAlign)
                        writer.Line("writer.AlignToByte();");
                    string self = member.BlobLengthIncludesSelf ? $" + {Num(member.BlobLengthBits / 8)}" : "";
                    writer.Line($"writer.WriteBits((ulong){name}.Length{self}, {Num(member.BlobLengthBits)});");
                    writer.Line($"writer.WriteBytes({name});");
                    break;
                case MemberShape.Pad:
                    writer.Line($"for (int written{i} = 0; written{i} < {Num(member.PadBits)}; written{i} += 64)");
                    writer.Line($"    writer.WriteBits(0, global::System.Math.Min(64, {Num(member.PadBits)} - written{i}));");
                    break;
            }
        }

        writer.Close();
    }

    private static void EmitCountAssignment(SourceWriter writer, TypeModel type, MemberModel count, ScalarModel scalar, int i)
    {
        List<MemberModel> arrays = [.. type.Members.Where(member => member.CountFrom == count.Name)];
        writer.Open("");
        writer.Line($"int shared{i} = {arrays[0].Name}.{CountOf(arrays[0])};");
        foreach (MemberModel other in arrays.Skip(1))
        {
            writer.Line($"if ({other.Name}.{CountOf(other)} != shared{i})");
            writer.Line($"    throw new {Codec}.CodecException({Quote($"The arrays that share {count.Name} differ in length.")});");
        }

        // Count widths stop at 32 (ModelBuilder), so only a narrower count can be outgrown by an int.
        long largest = scalar.Encoding == ScalarEncoding.SInt ? (1L << (scalar.Bits - 1)) - 1 : (1L << scalar.Bits) - 1;
        if (largest < int.MaxValue)
        {
            writer.Line($"if (shared{i} > {largest.ToString(CultureInfo.InvariantCulture)})");
            writer.Line($"    throw new {Codec}.CodecException({Quote($"{arrays[0].Name} holds more elements than {count.Name} can count.")});");
        }

        writer.Line($"{count.Name} = unchecked(({scalar.ClrType})shared{i});");
        writer.Close();
    }

    private static void EmitSelectorAssignment(SourceWriter writer, string selector, ScalarModel scalar, MemberModel union, LayoutCalculator layouts)
    {
        writer.Line($"{selector} = {union.Name} switch");
        writer.Line("{");
        foreach (TypeModel arm in layouts.ArmsOf(union.UnionType))
        {
            string literal = scalar.IsEnum
                ? $"unchecked(({scalar.ClrType})({scalar.IntegerType}){Num(arm.UnionCaseValue)}UL)"
                : $"unchecked(({scalar.ClrType}){Num(arm.UnionCaseValue)}UL)";
            writer.Line($"    {arm.FullName} => {literal},");
        }

        writer.Line($"    _ => throw new {Codec}.CodecException({Quote($"{union.Name} holds a type that is not an arm of {Plain(union.UnionType)}.")}),");
        writer.Line("};");
    }

    private static void EmitWriteValue(SourceWriter writer, ValueModel value, string expression)
    {
        switch (value.Kind)
        {
            case ValueKind.Struct:
                writer.Line($"{expression}.Write(ref writer);");
                break;
            case ValueKind.String:
                writer.Line($"writer.Write{StringMethod(value.String)}({expression});");
                break;
            case ValueKind.Scalar when value.Scalar is not null:
                writer.Line(WriteScalar(value.Scalar, expression));
                break;
        }
    }

    private static void EmitMeasure(SourceWriter writer, TypeModel type, LayoutCalculator layouts, LayoutModel layout, string modifiers)
    {
        writer.Line("/// <inheritdoc/>");
        writer.Open($"{modifiers} int MeasureBits()");
        if (layout.IsFixed && layout.IsComplete)
        {
            writer.Line($"return {Num(layout.Bits)};");
            writer.Close();
            return;
        }

        writer.Line(type.WireBase is not null ? "int bits = base.MeasureBits();" : "int bits = 0;");
        for (int i = 0; i < type.Members.Count; i++)
        {
            MemberModel member = type.Members[i];
            string name = member.Name;
            switch (member.Shape)
            {
                case MemberShape.Value when member.Value is not null:
                    writer.Line($"bits += {MeasureValue(member.Value, name, layouts)};");
                    break;
                case MemberShape.Array when member.Value is not null:
                    {
                        if (member.CountFrom is null)
                            writer.Line($"bits += {Num(member.CountBits)};");
                        int elementBits = layouts.ElementBits(member.Value);
                        if (elementBits >= 0)
                        {
                            writer.Line($"bits += {name}.{CountOf(member)} * {Num(elementBits)};");
                        }
                        else
                        {
                            writer.Line($"foreach (var element{i} in {name})");
                            writer.Line($"    bits += {MeasureValue(member.Value, $"element{i}", layouts)};");
                        }

                        break;
                    }

                case MemberShape.FixedArray when member.Value is not null:
                    {
                        int elementBits = layouts.ElementBits(member.Value);
                        if (elementBits >= 0)
                        {
                            writer.Line($"bits += {Num(member.FixedLength * elementBits)};");
                        }
                        else
                        {
                            writer.Line($"foreach (var element{i} in {name})");
                            writer.Line($"    bits += {MeasureValue(member.Value, $"element{i}", layouts)};");
                        }

                        break;
                    }

                case MemberShape.Union:
                    writer.Line($"bits += {name}.MeasureBits();");
                    break;
                case MemberShape.Blob:
                    if (member.BlobAlign)
                        writer.Line("bits = (bits + 7) & ~7;");
                    writer.Line($"bits += {Num(member.BlobLengthBits)} + (8 * {name}.Length);");
                    break;
                case MemberShape.Pad:
                    writer.Line($"bits += {Num(member.PadBits)};");
                    break;
            }
        }

        writer.Line("return bits;");
        writer.Close();
    }

    private static string ReadValue(ValueModel value)
    {
        return value.Scalar is { } scalar ? ReadScalar(scalar) : $"reader.Read{StringMethod(value.String)}()";
    }

    private static string ReadScalar(ScalarModel scalar)
    {
        string bits = Num(scalar.Bits);
        switch (scalar.Encoding)
        {
            case ScalarEncoding.Float32:
                return scalar.Components switch
                {
                    3 => "reader.ReadVector3()",
                    2 => "new global::System.Numerics.Vector2(reader.ReadFloat32(), reader.ReadFloat32())",
                    _ => "reader.ReadFloat32()",
                };
            case ScalarEncoding.Float64:
                return "reader.ReadFloat64()";
            case ScalarEncoding.PackedFloat:
                return scalar.Components switch
                {
                    3 => "reader.ReadPackedVector3()",
                    2 => "new global::System.Numerics.Vector2(reader.ReadPackedFloat(), reader.ReadPackedFloat())",
                    _ => "reader.ReadPackedFloat()",
                };
            case ScalarEncoding.SInt:
                return scalar.IsEnum
                    ? $"({scalar.ClrType})unchecked(({scalar.IntegerType})reader.ReadSignedBits({bits}))"
                    : $"unchecked(({scalar.ClrType})reader.ReadSignedBits({bits}))";
            default:
                if (scalar.IsBool)
                    return "reader.ReadBits(1) != 0";
                string raw = $"reader.ReadBits({bits})";
                string integer = scalar.IsSigned ? $"unchecked(({scalar.IntegerType})({scalar.UnsignedType}){raw})" : $"({scalar.IntegerType}){raw}";
                return scalar.IsEnum ? $"({scalar.ClrType}){integer}" : integer;
        }
    }

    private static string WriteScalar(ScalarModel scalar, string expression)
    {
        string bits = Num(scalar.Bits);
        switch (scalar.Encoding)
        {
            case ScalarEncoding.Float32:
                return scalar.Components switch
                {
                    3 => $"writer.WriteVector3({expression});",
                    2 => $"writer.WriteFloat32({expression}.X); writer.WriteFloat32({expression}.Y);",
                    _ => $"writer.WriteFloat32({expression});",
                };
            case ScalarEncoding.Float64:
                return $"writer.WriteFloat64({expression});";
            case ScalarEncoding.PackedFloat:
                return scalar.Components switch
                {
                    3 => $"writer.WritePackedVector3({expression});",
                    2 => $"writer.WritePackedFloat({expression}.X); writer.WritePackedFloat({expression}.Y);",
                    _ => $"writer.WritePackedFloat({expression});",
                };
            case ScalarEncoding.SInt:
                return scalar.IsEnum
                    ? $"writer.WriteSignedBits(({scalar.IntegerType}){expression}, {bits});"
                    : $"writer.WriteSignedBits({expression}, {bits});";
            default:
                if (scalar.IsBool)
                    return $"writer.WriteBits({expression} ? 1UL : 0UL, 1);";
                string integer = scalar.IsEnum ? $"({scalar.IntegerType}){expression}" : expression;
                return scalar.IsSigned
                    ? $"writer.WriteBits(unchecked(({scalar.UnsignedType}){integer}), {bits});"
                    : $"writer.WriteBits({integer}, {bits});";
        }
    }

    private static string MeasureValue(ValueModel value, string expression, LayoutCalculator layouts)
    {
        return value.Kind switch
        {
            ValueKind.Struct => $"{expression}.MeasureBits()",
            ValueKind.String => $"{Codec}.BitWriter.Measure{StringMethod(value.String)}({expression})",
            _ => Num(layouts.ValueLayout(value).Bits),
        };
    }

    /// <summary>
    /// The selector as <see cref="UnionCases.Label"/> numbers it: widened to long for a [SInt] selector, and for a [UInt] one read through the unsigned type of its size, as its Write puts it on the wire.
    /// </summary>
    private static string SelectorValue(string selector, ScalarModel scalar)
    {
        string integer = scalar.IsEnum ? $"({scalar.IntegerType}){selector}" : selector;
        if (scalar.Encoding == ScalarEncoding.SInt)
            return $"(long){integer}";
        return scalar.IsSigned ? $"unchecked((ulong)({scalar.UnsignedType}){integer})" : $"(ulong){integer}";
    }

    private static string StringMethod(StringEncoding encoding)
    {
        return encoding switch
        {
            StringEncoding.Wide => "WideString",
            StringEncoding.Narrow => "NarrowString",
            _ => "TerminatedWideString",
        };
    }

    private static string CountOf(MemberModel member)
    {
        return member.Collection == CollectionKind.Array ? "Length" : "Count";
    }

    private static string LayoutDataAttribute(LayoutModel layout)
    {
        string widths = string.Join(", ", layout.Widths.Select(width => Num(width)));
        string parts = string.Join(", ", layout.Parts.SelectMany(part => new[] { part.Shape, part.At, part.ElementBits }).Select(Num));
        return $"[{Codec}.WireLayoutData({Bool(layout.IsFixed)}, {Bool(layout.IsComplete)}, new byte[] {{ {widths} }}, new int[] {{ {parts} }})]";
    }

    private static string NamespaceOf(string assemblyName)
    {
        var builder = new StringBuilder();
        foreach (string segment in assemblyName.Split('.'))
        {
            if (builder.Length > 0)
                builder.Append('.');
            if (segment.Length == 0 || char.IsDigit(segment[0]))
                builder.Append('_');
            foreach (char c in segment)
                builder.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        }

        return builder.ToString();
    }

    private static string Plain(string? fullName)
    {
        return (fullName ?? "").Replace("global::", "");
    }

    private static string Quote(string text)
    {
        return "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }

    private static string Bool(bool value)
    {
        return value ? "true" : "false";
    }

    private static string Num(int value)
    {
        return value.ToString(CultureInfo.InvariantCulture);
    }

    private static string Num(ulong value)
    {
        return value.ToString(CultureInfo.InvariantCulture);
    }

    private static string Hex(ushort value)
    {
        return "0x" + value.ToString("X4", CultureInfo.InvariantCulture);
    }
}

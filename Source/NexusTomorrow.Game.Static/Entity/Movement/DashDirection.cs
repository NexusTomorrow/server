    /// A dash forward.
    /// </summary>
    Forward = 1,

    /// <summary>
    /// A dash backward.
    /// </summary>
    Backward = 2,

    /// <summary>
    /// A dash to the left.
    /// </summary>
    Left = 3,

    /// <summary>
    /// A dash to the right.
    /// </summary>
    Right = 4,
}
